import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createWorld,advanceWorld,getQuestBoard,nextWorldStep,renderQuestWorld,bindQuestWorld,WORLD_BUILDINGS} from '../js/quest-world.js';
const answer=(w,id,correct=true)=>advanceWorld(w,{type:'study-answer',id,correct}).world;
// Legacy version-one saves preserve their progress while gaining safe additive state.
const legacy={version:1,zone:'grove',studyTurns:17,energy:4,resources:{wood:5},buildings:{beacon:2},stats:{quests:4}};
const migrated=createWorld(legacy);
assert.equal(migrated.studyTurns,17);assert.equal(migrated.resources.wood,5);assert.equal(migrated.stats.quests,4);
assert.deepEqual(migrated.workshop,{progress:0,ready:0,collected:0});
assert.deepEqual(migrated.settlement,{expansions:0,deliveries:0});
assert.deepEqual(legacy,{version:1,zone:'grove',studyTurns:17,energy:4,resources:{wood:5},buildings:{beacon:2},stats:{quests:4}});
let w=createWorld({version:1,automation:{enabled:false}});for(let i=0;i<3;i++)w=answer(w,`crate-${i}`,false);
assert.equal(w.workshop.ready,1,'Every three saved answers grow the colony, including repairs');
assert.equal(w.workshop.progress,0);assert.equal(nextWorldStep(w).action.type,'collect-output');
assert.equal(answer(w,'crate-2',false).workshop.ready,1,'Retry must not duplicate production');
const collected=advanceWorld(w,{type:'collect-output',id:'collect-1'});
assert.equal(collected.world.resources.wood,1);assert.equal(collected.world.resources.crystal,1);assert.equal(collected.world.resources.seeds,4);
assert.equal(collected.world.workshop.collected,1);assert.equal(collected.world.workshop.ready,0);
assert.equal(collected.feedback.deltas.find(d=>d.key==='wood').amount,1);
assert.equal(advanceWorld(collected.world,{type:'collect-output',id:'collect-1'}).duplicate,true);
assert.equal(advanceWorld(collected.world,{type:'collect-output'}).changed,false);
const upgraded=createWorld({...migrated,workshop:{ready:2},buildings:{beacon:4,telescope:2}});
const rich=advanceWorld(upgraded,{type:'collect-output',id:'collect-rich'}).world;
assert.equal(rich.resources.wood,11);assert.equal(rich.resources.crystal,4,'Restoring landmarks increases crew output');
// Endless deliveries fund visible neighborhood expansion without generating external currency.
w=createWorld({version:1,energy:12,resources:{crops:4,lanterns:2,coins:2,wood:8,crystal:4}});
const delivered=advanceWorld(w,{type:'deliver',id:'delivery-1'});
assert.equal(delivered.world.settlement.deliveries,1);assert.equal(delivered.world.resources.coins,20);
assert.equal(delivered.world.resources.crops,2);assert.equal(delivered.world.resources.lanterns,1);
assert.equal(delivered.feedback.deltas.find(d=>d.key==='crops').amount,-2);
const expanded=advanceWorld(delivered.world,{type:'expand',id:'expansion-1'});
assert.equal(expanded.world.settlement.expansions,1);assert.equal(expanded.world.resources.coins,0);
assert.equal(advanceWorld(expanded.world,{type:'expand',id:'expansion-1'}).duplicate,true);
assert.ok(renderQuestWorld(expanded.world).includes('2 visible homes'));
assert.ok(!renderQuestWorld(w).includes('2 visible homes'));
assert.equal(advanceWorld({...w,zone:'grove'},{type:'deliver'}).changed,false);
assert.equal(advanceWorld({...w,energy:0},{type:'deliver'}).needsStudy,true);
// Every suggested action is actionable; mission suggestions guide missing resources and travel.
w=createWorld({version:1,automation:{enabled:false}});let suggested=nextWorldStep(w);assert.equal(suggested.action.type,'select-quest');
w=advanceWorld(w,suggested.action).world;assert.equal(nextWorldStep(w).action.type,'study');
for(let i=0;i<3;i++)w=answer(w,`mission-${i}`);
assert.equal(nextWorldStep(w).action.type,'claim-quest','A completed mission wins over collecting output');
w=advanceWorld(w,{type:'claim-quest'}).world;w=advanceWorld(w,{type:'collect-output'}).world;
const harvest=getQuestBoard(w).find(q=>q.objective==='harvested');
w=advanceWorld(w,{type:'select-quest',questId:harvest.id}).world;
assert.equal(nextWorldStep(w).action.type,'plant');
w=advanceWorld(w,nextWorldStep(w).action).world;
assert.equal(w.plots[0].readyAt,6);
const sprout=renderQuestWorld(w);
for(let i=0;i<3;i++)w=answer(w,`plant-${i}`);
assert.notEqual(renderQuestWorld(w),sprout,'Growing plants must visibly alter the map');
assert.ok(renderQuestWorld(w).includes('Ready to harvest'));
const maxed=createWorld({version:1,cycle:5,buildings:Object.fromEntries(Object.entries(WORLD_BUILDINGS).map(([key,spec])=>[key,spec.maxLevel]))});
assert.ok(getQuestBoard(maxed).every(q=>q.objective!=='built'),'A fully restored colony never receives an impossible upgrade mission');
const broken=createWorld({version:1,workshop:{progress:Infinity,ready:Infinity,collected:-1},settlement:{expansions:-1,deliveries:'oops'},journal:[{message:'valid',turn:-1},{}]});
assert.equal(broken.workshop.ready,50);assert.equal(broken.settlement.expansions,0);assert.equal(broken.journal.length,1);
for(let i=0;i<20;i++)w=answer(w,`journal-${i}`);
assert.equal(w.journal.length,8);assert.deepEqual(createWorld(JSON.parse(JSON.stringify(w))),w);
// Rejected feedback is rendered and save failures remain usable; taps cannot race.
const markup=renderQuestWorld(w,{mode:'coop',guildName:'<Guild>',feedback:{tone:'hint',message:'Answer first'},needsStudy:true});
assert.ok(markup.includes('&lt;Guild&gt;'));assert.ok(markup.includes('Your card mastery stays personal'));assert.ok(markup.includes('Answer first'));
assert.ok(markup.includes('qw-guide'));assert.ok(markup.includes('data-qw-study'));assert.ok(markup.includes('qw-journal'));
const dom=new JSDOM(renderQuestWorld(createWorld()));
let release,calls=0;
const root=dom.window.document.querySelector('.quest-world');
const dispose=bindQuestWorld(root,{onAction:()=>{calls++;return new Promise(resolve=>release=resolve);}});
const button=root.querySelector('[data-qw-action]');button.click();button.click();
assert.equal(calls,1);assert.equal(root.getAttribute('aria-busy'),'true');release();await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(root.hasAttribute('aria-busy'),false);assert.equal(button.disabled,false);dispose();
assert.equal(typeof bindQuestWorld(null),'function');
console.log('Colony guidance: legacy migration, answer-powered production, delivery/expansion economy, visible crop/map changes, attainable missions, feedback, and tap isolation passed.');
