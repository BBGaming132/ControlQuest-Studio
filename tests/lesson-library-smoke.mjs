import assert from 'node:assert/strict';
import { LESSONS, matchLesson, filterDecks, filterDeckCards } from '../js/lesson-catalog.js';
import { buildImportBundle } from '../js/flashcard-engine.js';
assert.equal(LESSONS.filter(l=>l.domainId!=='practice').length,60);
assert.equal(matchLesson('Domain 1 - Audit Project Management - June 23')?.id,'d1-t05');
assert.equal(matchLesson('1B1Audit Project Management','d1')?.id,'d1-t05');
assert.equal(matchLesson('Network & Endpoint Security')?.id,'d5-t04');
assert.equal(matchLesson('BIA')?.id,'d4-t12');
assert.equal(matchLesson('Audit Project Management','d2'),null);
assert.equal(matchLesson('Audit'),null);
const question={question:'Which approach is best?',choices:{A:'Risk based',B:'Convenient'},correctAnswer:'A',domainNumber:1,domain:'Domain 1',knowledgeStatement:'1B1Audit Project Management'};
const bundle=buildImportBundle({questions:[question],title:'Odd filename',lessonId:'d1-t05',uid:'u',groupId:'g',scope:'Guild'});
assert.equal(bundle.cards[0].lessonId,'d1-t05');
assert.equal(bundle.decks[0].lessonId,'d1-t05');
const mixed=buildImportBundle({questions:[question,{...question,question:'Second domain question',domainNumber:4,domain:'Domain 4',knowledgeStatement:'Business Impact Analysis'}],title:'Mixed',uid:'u',groupId:'g',scope:'Guild'});
assert.deepEqual(filterDeckCards(mixed.cards,{domain:'d4'}).map(c=>c.lessonId),['d4-t12']);
assert.equal(filterDecks(mixed.decks,mixed.cards,{domain:'d5'}).length,0);
assert.ok(filterDecks(mixed.decks,mixed.cards,{domain:'d1',kind:'master'}).length);
assert.equal(filterDecks(bundle.decks,bundle.cards,{search:'Audit Project Management',scope:'Personal'}).length,0);
assert.equal(filterDecks(bundle.decks,bundle.cards,{search:'audit project',kind:'lesson'}).length,1);
const legacy={id:'old',scopeKey:'Guild:g',kind:'lesson',title:'BIA',scope:'Guild'};
const oldCard={id:'old-card',scopeKey:'Guild:g',deckIds:['old'],question:'Legacy card'};
assert.equal(filterDecks([legacy],[oldCard],{domain:'d4',lesson:'d4-t12'}).length,1);
console.log('Lesson matching, legacy decks, mixed imports and shared filter tests passed.');
