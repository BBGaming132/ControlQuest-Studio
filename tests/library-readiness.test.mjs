import assert from 'node:assert/strict';
import {LESSONS,matchLesson,lessonMatchDetails} from '../js/lesson-catalog.js';
import {auditLibrary,auditIncomingQuestions} from '../js/library-audit.js';
import {parseQaePaste} from '../js/qae-parser.js';
import {createBatchPlan,runBatchImport,createBatchCheckpoint,batchOperationId} from '../js/batch-importer.js';
import {LESSON_GUIDANCE,getLessonGuidance,GUIDANCE_SOURCES} from '../js/lesson-guidance.js';
assert.deepEqual([1,2,3,4,5].map(n=>LESSONS.filter(l=>l.domainId===`d${n}`).length),[10,11,8,16,15]);
assert.equal(matchLesson('Domain 1 - Audit Proejct Management.docx')?.id,'d1-t05');
assert.equal(lessonMatchDetails('Audit Proejct Management').method,'spelling');
assert.equal(matchLesson('IT Assset Management')?.id,'d4-t02');
assert.equal(matchLesson('IT Policies Standards Procedures and Practices')?.id,'d2-t03');
assert.equal(matchLesson('Audit'),null);
assert.equal(matchLesson('BIP'),null,'short acronym typos must never map to another topic');
assert.equal(matchLesson('Domain 2 - Audit Proejct Management.docx'),null,'conflicting explicit domain is not ignored');
assert.equal(matchLesson('Audit Project Management and Business Impact Analysis'),null,'mixed title needs review');
assert.equal(matchLesson('Domain 1 Audit Project Management','d2'),null);
const deck={id:'d',title:'Audit Proejct Management',scope:'Personal',scopeKey:'personal_u'};
const card={id:'q',question:'Which approach is best?',choices:{A:'Risk based',B:'Convenience'},correctAnswer:'A',scope:'Personal',scopeKey:'personal_u',deckIds:['d']};
const audit=auditLibrary({decks:[deck],cards:[card],uid:'u'});
assert.equal(audit.categorization.operations.length,2);
assert.equal(audit.categorization.operations[1].patch.lessonId,'d1-t05');
const manual=auditLibrary({decks:[deck],cards:[{...card,categoryOverride:true,lessonId:''}],uid:'u'});
assert.ok(!manual.categorization.operations.some(o=>o.kind==='card'),'deliberately unlinked manual card stays unlinked');
assert.equal(auditIncomingQuestions([{...card,choices:{A:'Convenience',B:'Risk based'},correctAnswer:'B'}],[card]).existingDuplicates,1);
const exportText=`question 1 of 1\nQuestion\nWhich approach is best?\na) Risk based\nb) Convenience\nCorrect answer: A\nExplanation:\nA) Address the business risk.\nB) Convenience is not the objective.\nDomain 1 Example\n`;
const parsed=parseQaePaste(exportText);
assert.equal(parsed.questions.length,1);
assert.deepEqual(parsed.questions[0].choices,{A:'Risk based',B:'Convenience'});
assert.equal(parsed.questions[0].justifications.A,'Address the business risk.');
assert.equal(parseQaePaste(exportText.replace('Correct answer: A','Correct answer: D')).questions.length,0,'unavailable answer choices cannot become importable cards');
const plan=await createBatchPlan([{name:'Audit Proejct Management.txt',size:exportText.length,text:async()=>exportText}],{scope:'Personal',uid:'u',readFile:f=>f.text()});
assert.equal(plan.items[0].title,'Audit Proejct Management');
assert.equal(plan.items[0].lessonId,'d1-t05');
assert.equal(plan.items[0].requiresReview,true);
assert.ok(plan.items[0].warnings.some(w=>w.includes('spelling')));
const supplemental=await createBatchPlan([{name:'Audit Project Management.txt',size:exportText.length,text:async()=>exportText}],{scope:'Personal',uid:'u',source:'Udemy supplemental',readFile:f=>f.text()});
let savedBundle=null;
await runBatchImport(supplemental,{uid:'u',checkpoint:createBatchCheckpoint({uid:'u',storage:null}),importItem:async(item,{bundle})=>{savedBundle=bundle;}});
assert.equal(savedBundle.cards[0].source,'Udemy supplemental');
assert.deepEqual(savedBundle.cards[0].sources,['Udemy supplemental']);
assert.notEqual(await batchOperationId({...supplemental.items[0],source:'ISACA QAE Paste'},{uid:'u'}),await batchOperationId(supplemental.items[0],{uid:'u'}),'source changes do not reuse completed checkpoint');
const examText=exportText+'\n'+exportText.replace('question 1 of 1','question 2 of 2').replace('Which approach is best?','Which second approach is best?').replace('Domain 1 Example','Domain 2 Example');
const exam=await createBatchPlan([{name:'Practice Exam 1.txt',size:examText.length,text:async()=>examText}],{scope:'Personal',uid:'u',source:'Practice exam',sharePublic:false,readFile:f=>f.text()});
exam.items[0].confirmed=true;
assert.equal(exam.items[0].lessonId,'pe-1');
const examResult=await runBatchImport(exam,{uid:'u',checkpoint:createBatchCheckpoint({uid:'u',storage:null}),importItem:async(item,{bundle})=>{savedBundle=bundle;}});
assert.equal(examResult.results[0].status,'complete');
assert.deepEqual(savedBundle.cards.map(c=>c.domainNumber),[1,2],'practice collection preserves question domains');
assert.ok(savedBundle.cards.every(c=>c.practiceExamId==='pe-1'));
assert.equal(Object.keys(LESSON_GUIDANCE).length,60);
for(const lesson of LESSONS.filter(l=>/^d[1-5]$/.test(l.domainId))){
 const guidance=getLessonGuidance(lesson.id);assert.equal(guidance.lessonId,lesson.id);assert.ok(guidance.prompt.length>30);assert.ok(guidance.sources.length);
 for(const source of guidance.sources){assert.ok(source.title);assert.equal(new URL(source.url).protocol,'https:');assert.match(new URL(source.url).hostname,/(?:^|\.)(?:nist\.gov|isaca\.org|postgresql\.org)$/);}
}
assert.equal(getLessonGuidance('unknown'),null);
assert.equal(Object.keys(GUIDANCE_SOURCES).length,28);
console.log('Library readiness: 60 lessons, conservative spelling matches, manual category preservation, parser variants, exact duplicates and sourced guidance passed.');
