import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {inferInitialCount,sessionProgress,renderSessionProgress} from '../js/study-session.js';
assert.equal(inferInitialCount(['a','b','c','b','a']),3);
assert.equal(inferInitialCount([{id:'a',scopeKey:'one'},{id:'a',scopeKey:'two'},{id:'a',scopeKey:'one'}]),2);
assert.equal(inferInitialCount([]),0);
const first=sessionProgress({total:3,initialCount:3,index:1,answered:true});
assert.equal(first.initialDone,2);assert.equal(first.reviewTotal,0);assert.equal(first.remaining,1);
const review=sessionProgress({total:5,initialCount:3,index:3});
assert.equal(review.initialDone,3);assert.equal(review.reviewDone,0);assert.equal(review.currentType,'review');
assert.equal(sessionProgress({total:6,initialCount:3,index:5,answered:true}).reviewDone,3);
assert.equal(sessionProgress({total:2,initialCount:0,index:0}).currentType,'review');
assert.equal(sessionProgress({total:3,initialCount:100,index:99}).completed,3);
const dom=new JSDOM(renderSessionProgress({total:5,initialCount:3,index:3,answered:true}));
const doc=dom.window.document;
assert.equal(doc.querySelector('[role="progressbar"]').getAttribute('aria-valuenow'),'4');
assert.match(doc.querySelector('[role="progressbar"]').getAttribute('aria-valuetext'),/review 1 of 2/);
assert.equal(doc.querySelector('.cq-session-review').dataset.total,'2');
assert.equal(doc.querySelector('.cq-session-review i').style.width,'50%');
assert.equal(doc.querySelector('.cq-session-lesson i').style.width,'100%');
assert.match(doc.querySelector('.cq-session-current').textContent,/Review question/);
console.log('Session progress: initial, repeated, resumed, accessible counts passed');
