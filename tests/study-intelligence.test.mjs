import assert from 'node:assert/strict';
import { buildImportBundle, defaultProgress, rateCard, progressKey, cardMastery, hasUnresolvedMiss, buildStudyQueue, isDue } from '../js/flashcard-engine.js';
import { studyIdentity, uniqueStudyCards, buildDomainAnalytics, buildDailyPlan } from '../js/study-intelligence.js';

const now=new Date('2026-10-24T14:00:00Z');
const practice=buildImportBundle({uid:'u',scope:'Personal',title:'Practice Exam 1',lessonId:'pe-1',questions:[
  {question:'Audit exam question',choices:{A:'Risk',B:'Convenience'},correctAnswer:'A',domain:'Domain 1',domainNumber:1,domainName:'Information Systems Auditing Process',knowledgeStatement:'Audit Project Management'},
  {question:'Security exam question',choices:{A:'Encrypt',B:'Ignore'},correctAnswer:'A',domain:'Domain 5',domainNumber:5,domainName:'Protection of Information Assets'}
]});
assert.equal(practice.decks[0].lessonId,'pe-1');
assert.equal(practice.cards[0].domainNumber,1);
assert.equal(practice.cards[0].lessonId,'d1-t05');
assert.equal(practice.cards[1].domainNumber,5);
assert.equal(practice.cards[1].domain,'Domain 5');
assert.equal(practice.cards[1].practiceExamId,'pe-1');
const practiceAnalytics=buildDomainAnalytics(practice.cards,{},[],{now,uid:'u',decks:practice.decks});
assert.equal(practiceAnalytics.domains.find(d=>d.id==='d1').total,1);
assert.equal(practiceAnalytics.domains.find(d=>d.id==='d5').total,1);
assert.equal(practiceAnalytics.unassigned,0);
const card=(id,domain=1,extra={})=>({id,scopeKey:'personal_u',scope:'Personal',ownerUid:'u',question:`Question ${id}`,choices:{A:'Primary answer',B:'Distractor'},correctAnswer:'A',domainNumber:domain,...extra});
const first=card('one',1,{lessonId:'d1-t05',wasCorrectAtImport:false});
const duplicate=card('public-one',1,{...first,id:'public-one',scopeKey:'public',scope:'Public',ownerUid:'another',choices:{A:'Distractor',B:'Primary answer'},correctAnswer:'B'});
assert.equal(studyIdentity(first),studyIdentity(duplicate),'reordered choices should share a study identity');
const p0=defaultProgress(first,'u');
const failed=rateCard(first,p0,'Again',undefined,now);
assert.equal(failed.state,'learning');assert.equal(failed.incorrectCount,1);assert.equal(failed.successfulRecallStreak,0);
assert.equal(failed.dueAt,'2026-10-24T14:01:00.000Z');
assert.equal(hasUnresolvedMiss(first,failed),true);
assert.throws(()=>rateCard(first,p0,'Perfect',undefined,now),/Choose/);
assert.throws(()=>rateCard(first,p0,'Good',undefined,new Date('invalid')),/valid/);
const good1=rateCard(first,failed,'Good',undefined,new Date('2026-10-24T14:01:00Z'));
assert.equal(good1.dueAt,'2026-10-24T14:11:00.000Z');
const good2=rateCard(first,good1,'Good',undefined,new Date('2026-10-24T14:11:00Z'));
assert.equal(hasUnresolvedMiss(first,good2),false,'two successful recalls repair the missed queue');
assert.equal(cardMastery(good2),'Learning','repair is not long-term mastery');
const review=rateCard(first,good2,'Good',undefined,new Date('2026-10-25T14:11:00Z'));
assert.equal(review.state,'review');assert.equal(review.intervalDays,1);
const graduated=rateCard(first,defaultProgress(first,'u'),'Easy',undefined,now);
assert.equal(graduated.intervalDays,4);
const ahead=rateCard(first,graduated,'Easy',undefined,new Date('2026-10-24T14:02:00Z'));
assert.equal(ahead.intervalDays,4,'pressing Easy ahead of schedule must not inflate intervals');
assert.equal(ahead.dueAt,graduated.dueAt);assert.equal(ahead.validatedRecalls,1);
let spaced=rateCard(first,graduated,'Easy',undefined,new Date(graduated.dueAt));
assert.equal(spaced.intervalDays,15);
spaced=rateCard(first,spaced,'Easy',undefined,new Date(spaced.dueAt));
assert.equal(spaced.intervalDays,58);assert.equal(cardMastery(spaced),'Mastered');
const lapsed=rateCard(first,spaced,'Again',undefined,new Date(spaced.dueAt));
assert.equal(lapsed.state,'relearning');assert.equal(lapsed.lapses,1);assert.equal(cardMastery(lapsed),'Learning');
const settings={learningStepsMinutes:[1,5,15],relearningStepsMinutes:[2,20]};
const relapse=rateCard(first,{...spaced,dueAt:now.toISOString()},'Again',settings,now);
assert.equal(relapse.dueAt,'2026-10-24T14:02:00.000Z');
const hardRelapse=rateCard(first,relapse,'Hard',settings,new Date('2026-10-24T14:02:00Z'));
assert.equal(hardRelapse.state,'relearning');assert.equal(hardRelapse.dueAt,'2026-10-24T14:08:00.000Z');
const goodRelapse=rateCard(first,relapse,'Good',settings,new Date('2026-10-24T14:02:00Z'));
assert.equal(goodRelapse.state,'relearning');assert.equal(goodRelapse.dueAt,'2026-10-24T14:22:00.000Z');
const backToReview=rateCard(first,goodRelapse,'Good',settings,new Date('2026-10-24T14:22:00Z'));
assert.equal(backToReview.state,'review');
assert.equal(isDue({dueAt:'malformed'},now),true,'invalid saved dates should be recoverable');

const second=card('two',5,{lessonId:'d5-t03'}),third=card('three',4),uncategorized=card('unknown',null);
const recovered={...good2,lastReviewedAt:now.toISOString(),dueAt:'2026-10-25T14:00:00Z'};
const secondProgress={...defaultProgress(second,'u'),state:'review',repetitions:4,correctCount:3,incorrectCount:1,answerStreak:1,successfulRecallStreak:1,lastRating:'Good',lastReviewedAt:'2026-10-23T10:00:00Z',dueAt:'2026-10-24T12:00:00Z',intervalDays:7};
const progress={ [progressKey(first)]:failed,[progressKey(duplicate)]:recovered,[progressKey(second)]:secondProgress };
const cards=[first,duplicate,second,third,uncategorized];
const unique=uniqueStudyCards(cards,progress,[],{uid:'u'});
assert.equal(unique.length,4);assert.equal(unique.find(c=>c.question===first.question).scopeKey,'public','latest saved progress wins across copies');
let analytics=buildDomainAnalytics(cards,progress,[],{now,uid:'u'});
assert.equal(analytics.totals.total,4);assert.equal(analytics.duplicateCopies,1);assert.equal(analytics.unassigned,1);
assert.equal(analytics.domains.find(d=>d.id==='d1').total,1);assert.equal(analytics.domains.find(d=>d.id==='d1').missed,0);
assert.equal(analytics.domains.find(d=>d.id==='d5').reviewMisses,1);assert.equal(analytics.domains.find(d=>d.id==='d5').missed,1);
assert.equal(analytics.domains.find(d=>d.id==='d4').unseen,1);
assert.equal(analytics.domains.find(d=>d.id==='d1').missingUploads,null,'cannot invent missing QAE counts');
assert.equal(analytics.domains.reduce((sum,d)=>sum+d.examWeight,0),100);
assert.equal(analytics.domains.reduce((sum,d)=>sum+d.total,0)+analytics.unassigned,analytics.totals.total);
analytics=buildDomainAnalytics(cards,progress,[],{now,uid:'u',expectedTotals:{d1:10}});
assert.equal(analytics.domains[0].missingUploads,9);
const conflict=card('conflicting-domain',2,{question:first.question,choices:first.choices});
assert.equal(buildDomainAnalytics([first,conflict],{},[],{now}).categorizationConflicts,1,'cross-domain duplicates need category correction');
assert.equal(buildDomainAnalytics([first,conflict],{},[],{now}).unassigned,1);
const foreignMiss=card('foreign',2,{ownerUid:'another',wasCorrectAtImport:false});
assert.equal(buildDomainAnalytics([foreignMiss],{},[],{now,uid:'u'}).totals.missed,0,'another member\'s import result is not this user\'s missed question');
assert.equal(buildDomainAnalytics([foreignMiss],{},[],{now,uid:'u'}).totals.sourceImportedMisses,1);
const fakeMastered={...spaced,lastReviewedAt:now.toISOString(),dueAt:'2027-01-01T00:00:00Z'};
const incorrectEvent={id:'wrong-easy',uid:'u',cardId:first.id,scopeKey:first.scopeKey,reviewedAt:now.toISOString(),correct:false,rating:'Easy'};
assert.equal(buildDomainAnalytics([first],{[progressKey(first)]:fakeMastered},[incorrectEvent],{now,uid:'u'}).totals.mastered,0,'historical wrong answer rated Easy cannot be mastered');
assert.equal(buildDomainAnalytics([first],{[progressKey(first)]:fakeMastered},[incorrectEvent],{now,uid:'u'}).totals.missed,1);
const unresolvedConflict={...second,answerConflict:true};
assert.equal(buildDailyPlan([unresolvedConflict],{},[],{now}).questionCount,0,'answer conflicts do not enter graded plans');
const foreignProgress={...fakeMastered,uid:'another'};
assert.equal(buildDomainAnalytics([first],{[progressKey(first)]:foreignProgress},[],{now,uid:'u'}).totals.mastered,0,"a mixed progress map cannot use another user's mastery");
const unknownGuildMiss=card('unknown-guild',1,{scope:'Guild',scopeKey:'guild_g',ownerUid:undefined,wasCorrectAtImport:false});
assert.equal(buildDomainAnalytics([unknownGuildMiss],{},[],{now,uid:'u'}).totals.missed,0,'unattributed shared import results are not personal misses');
const wrongUidEvent={...incorrectEvent,id:'other-user',uid:'another'};
assert.equal(buildDomainAnalytics([first],{[progressKey(first)]:fakeMastered},[wrongUidEvent],{now,uid:'u'}).totals.mastered,1,'another user\'s review cannot override mastery');

const todayEvents=[{id:'a',uid:'u',cardId:first.id,scopeKey:first.scopeKey,reviewedAt:'2026-10-24T12:00:00Z',correct:true},
{id:'b',uid:'u',cardId:duplicate.id,scopeKey:duplicate.scopeKey,reviewedAt:'2026-10-24T12:02:00Z',correct:true}];
const plan=buildDailyPlan(cards,progress,todayEvents,{now,uid:'u',minutes:3,targetQuestions:2,dailyGoal:2});
assert.equal(plan.questionCount,2);assert.equal(plan.completedToday,1,'reviewing copies counts one question toward the daily goal');
assert.equal(plan.remainingGoal,1);assert.equal(plan.cards[0].id,second.id,'unresolved personal misses are first');
assert.equal(plan.recommendationType,'Local rules-based study coach');
assert.deepEqual(buildDailyPlan(cards,progress,[],{now,uid:'u',minutes:3}).cards.map(c=>c.studyIdentity),buildDailyPlan(cards,progress,[],{now,uid:'u',minutes:3}).cards.map(c=>c.studyIdentity),'plans should be deterministic');
assert.equal(buildDailyPlan([],{},[],{now}).questionCount,0);
assert.ok(buildStudyQueue([first],{[progressKey(first)]:good2},{mode:'missed'}).length===0,'resolved misses leave the current repair queue');
console.log('Study intelligence: scheduling transitions, relearning, review-ahead protection, deduplication, personal misses, domain analytics and daily plan tests passed.');
