import assert from 'node:assert/strict';
import { buildPublicContributions, aggregateCommunityLibrary } from '../js/community-library.js';
import { filterDecks, inferDeckLesson } from '../js/lesson-catalog.js';
import { loadCommunityLibrary, savePublicContributions, savePublicLessonStatus } from '../js/firebase-service.js';
const storage=new Map();globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)};
const deck={id:'legacy',scope:'Guild',scopeKey:'guild_g',title:'Old upload',createdBy:'Ty',kind:'lesson'};
const one={id:'old',deckIds:['legacy'],scopeKey:'guild_g',question:' Which method is BEST? ',choices:{A:'Risk based',B:'Convenient'},correctAnswer:'A',justifications:{A:'Prioritize risk',B:'Not sufficient'},knowledgeStatement:'Audit Project Management',domainNumber:1,userAnswerAtImport:'B',wasCorrectAtImport:false};
assert.equal(inferDeckLesson(deck,[one]).id,'d1-t05');
const a=await buildPublicContributions({deck,cards:[one],uid:'a',name:'Bennett'});
const two={...one,question:'Which method is BEST?',choices:{A:'Convenient',B:'Risk based'},correctAnswer:'B',justifications:{B:'Prioritize risk',A:'Not sufficient'}};
const b=await buildPublicContributions({deck,cards:[two],uid:'b',name:'Ty'});
assert.equal(a[0].fingerprint,b[0].fingerprint);
assert.equal((await buildPublicContributions({deck,cards:[one,one],uid:'a',name:'Bennett'})).length,1);
assert.notEqual(a[0].id,b[0].id);
assert.equal(a[0].userAnswerAtImport,undefined);
assert.equal(a[0].wasCorrectAtImport,undefined);
let shared=aggregateCommunityLibrary([...a,...b]);
assert.equal(shared.decks.length,1);assert.equal(shared.cards.length,1);
assert.equal(shared.cards[0].submissionCount,2);assert.equal(shared.cards[0].answerConflict,false);
assert.equal(shared.cards[0].explanationDifferences,false);assert.deepEqual(new Set(shared.cards[0].contributors),new Set(['Bennett','Ty']));
const conflicting=await buildPublicContributions({deck,cards:[{...two,correctAnswer:'A'}],uid:'b',name:'Ty'});
assert.equal(aggregateCommunityLibrary([...a,...conflicting]).cards[0].answerConflict,true);
const unique=await buildPublicContributions({deck,cards:[{...one,question:'Another question'}],uid:'c',name:'Another member'});
assert.equal(aggregateCommunityLibrary([...a,...b,...unique]).cards.length,2);
await savePublicContributions('a',a,`${deck.scopeKey}|${deck.id}`);
await savePublicContributions('b',b,`${deck.scopeKey}|${deck.id}`);
await savePublicContributions('a',a,`${deck.scopeKey}|${deck.id}`);
assert.equal((await loadCommunityLibrary()).contributions.length,2);
const corrected={...deck,categoryOverride:true,lessonId:'d2-t05',domainId:'d2'};
const reclassified=await buildPublicContributions({deck:corrected,cards:[one],uid:'a',name:'Bennett'});
assert.equal(reclassified[0].id,a[0].id);
await savePublicContributions('a',reclassified,`${deck.scopeKey}|${deck.id}`);
shared=aggregateCommunityLibrary((await loadCommunityLibrary()).contributions);
assert.equal(shared.decks.length,2);assert.ok(shared.decks.some(d=>d.lessonId==='d2-t05'));
assert.equal(filterDecks([corrected],[one],{domain:'d2',lesson:'d2-t05'}).length,1);
assert.equal(filterDecks([corrected],[one],{domain:'d1'}).length,0);
await savePublicContributions('a',[],`${deck.scopeKey}|${deck.id}`);
assert.equal((await loadCommunityLibrary()).contributions.length,1);
await assert.rejects(savePublicContributions('a',b));
await savePublicLessonStatus('a','d1-t05',{completed:true,updatedByName:'Bennett'});
assert.equal((await loadCommunityLibrary()).statuses['d1-t05'].completed,true);
await assert.rejects(savePublicLessonStatus('a','bad',{completed:true}));
console.log('Community deduplication, reordered choices, answer conflicts, privacy, reclassification, contributor ownership and shared checkoffs passed.');
