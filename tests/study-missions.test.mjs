import assert from 'node:assert/strict';
import {buildStudyMission,todoistMissionLinks,normalizeTodoistTaskUrl,normalizeEversteadUrl,DEFAULT_EVERSTEAD_URL} from '../js/study-missions.js';
const draft=buildStudyMission({minutes:5,questionCount:7,cards:[{question:'PRIVATE QUESTION'}]},{recurring:true});
assert.equal(draft.title,'Study CISA: 7 questions (5 minutes)');
assert.equal(draft.status,'draft');assert.equal(draft.requiresReview,true);
assert.equal(draft.due,'every day');assert(!JSON.stringify(draft).includes('PRIVATE QUESTION'));
const links=todoistMissionLinks(draft);
const mobile=new URL(links.mobile),desktop=new URL(links.desktop);
assert.equal(mobile.protocol,'todoist:');assert.equal(mobile.hostname,'addtask');
assert.equal(mobile.searchParams.get('content'),draft.title);assert.equal(mobile.searchParams.get('date'),'every day');
assert.equal(desktop.hostname,'openquickadd');assert.equal(desktop.searchParams.get('description'),draft.description);assert.equal(desktop.searchParams.get('content'),draft.title+' every day');
assert.equal(new URL(todoistMissionLinks(buildStudyMission()).mobile).searchParams.has('date'),false);
assert.equal(buildStudyMission({minutes:999,questionCount:999}).minutes,60);
assert.equal(buildStudyMission({minutes:999,questionCount:999}).questions,100);
assert.equal(normalizeTodoistTaskUrl('https://app.todoist.com/app/task/6abc?utm_source=test#x'),'https://app.todoist.com/app/task/6abc');
assert.equal(normalizeTodoistTaskUrl('https://todoist.com/showTask?id=123'),'https://todoist.com/showTask?id=123');
assert.equal(normalizeTodoistTaskUrl(''),'');
for(const url of ['javascript:alert(1)','https://todoist.com.attacker.com/app/task/id','https://secret@todoist.com/app/task/id','https://app.todoist.com/app/today','https://app.todoist.com:444/app/task/abc'])assert.throws(()=>normalizeTodoistTaskUrl(url));
assert.equal(normalizeEversteadUrl(''),DEFAULT_EVERSTEAD_URL);
assert.equal(normalizeEversteadUrl('https://example.com/colony'),'https://example.com/colony');
for(const url of ['http://example.com','https://secret@example.com','https://example.com/?token=private','https://example.com/#access_token=private'])assert.throws(()=>normalizeEversteadUrl(url));
console.log('Study mission privacy and review-first task links passed.');
